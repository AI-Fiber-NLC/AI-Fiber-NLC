"""
PyTorch Dataset wrapper for NLC simulation data.

Provides lazy-loading access to .npz files generated by the simulator.
"""

from __future__ import annotations

import numpy as np
import torch
from pathlib import Path
from typing import Optional, List


class NLCDataset(torch.utils.data.Dataset):
    """
    PyTorch Dataset for (impaired, clean) symbol pairs.

    Loads one power-point .npz file on construction.
    Returns individual symbol pairs on __getitem__.
    """

    def __init__(
        self,
        data_dir: Path,
        scene_name: str,
        tx_power_dbm: float,
        transform: Optional[callable] = None,
    ):
        """
        Args:
            data_dir: root data directory (e.g. Path("data/raw"))
            scene_name: scene folder name (e.g. "MVB-1")
            tx_power_dbm: transmit power in dBm (e.g. 1.0)
            transform: optional callable applied to each sample pair
        """
        self.data_dir = Path(data_dir)
        self.scene_name = scene_name
        self.tx_power_dbm = tx_power_dbm
        self.transform = transform

        self.file_path = self.data_dir / scene_name / self._power_filename(tx_power_dbm)

        # Lazy load — data is only read when first accessed
        self._rx: Optional[np.ndarray] = None
        self._tx: Optional[np.ndarray] = None
        self._metadata: dict = {}

    @staticmethod
    def _power_filename(power_dbm: float) -> str:
        """Generate .npz filename for a given power level.

        Format: p_<power_dBm>dBm.npz
        e.g. p_1.0dBm.npz, p_-3.0dBm.npz
        """
        return f"p_{power_dbm:.1f}dBm.npz"

    def _load(self) -> None:
        """Load .npz file into memory (called once on first access)."""
        if self._rx is None:
            data = np.load(self.file_path)
            self._rx = data["rx_signal"]
            self._tx = data["tx_signal"]
            self._metadata = {
                k: data[k].item() for k in data.files
                if k not in ("rx_signal", "tx_signal")
            }

    def __len__(self) -> int:
        self._load()
        return len(self._rx)

    def __getitem__(self, idx: int) -> tuple:
        self._load()

        rx_sample = self._rx[idx]
        tx_sample = self._tx[idx]

        # Ensure we have numpy arrays (not scalars) for torch.from_numpy
        if not isinstance(rx_sample, np.ndarray):
            rx_sample = np.array(rx_sample)
            tx_sample = np.array(tx_sample)

        # Convert complex to real-valued (2 channels: I and Q)
        if np.issubdtype(self._rx.dtype, np.complexfloating):
            rx_tensor = torch.view_as_real(torch.from_numpy(rx_sample.copy()))
            tx_tensor = torch.view_as_real(torch.from_numpy(tx_sample.copy()))
        else:
            rx_tensor = torch.from_numpy(rx_sample)
            tx_tensor = torch.from_numpy(tx_sample)

        if self.transform:
            rx_tensor, tx_tensor = self.transform(rx_tensor, tx_tensor)

        return rx_tensor, tx_tensor

    @property
    def metadata(self) -> dict:
        """Return .npz metadata (scene name, seed, power, etc.)."""
        self._load()
        return self._metadata

    @classmethod
    def list_power_files(cls, data_dir: Path, scene_name: str) -> List[float]:
        """
        Scan a scene directory and return list of available power levels.

        Returns:
            Sorted list of tx_power_dbm values found in the directory.
        """
        scene_dir = Path(data_dir) / scene_name
        if not scene_dir.exists():
            return []

        powers = []
        for f in scene_dir.glob("p_*dBm.npz"):
            # Parse "p_-3.0dBm" → -3.0
            name = f.stem  # e.g. "p_-3.0dBm"
            power_str = name[2:-4]  # strip "p_" and "dBm"
            powers.append(float(power_str))
        return sorted(powers)
